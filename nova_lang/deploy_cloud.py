def _aws_schedule_expression(expr):
    """Convert 5-field cron to an EventBridge Scheduler cron() expression.

    EventBridge uses a 6-field cron with `?` in day-of-month or
    day-of-week (it forbids specific values in both). Raises
    ManifestError for anything we can't translate honestly.
    """
    fields = expr.split()
    if len(fields) != 5:
        raise ManifestError(
            "cron schedule '%s' is not 5-field; EventBridge conversion "
            "needs 'min hour dom month dow'" % expr)
    minute, hour, dom, month, dow = fields
    if dom != "*" and dow != "*":
        raise ManifestError(
            "cron schedule '%s' pins both day-of-month and day-of-week; "
            "EventBridge forbids that — pick one" % expr)
    if dow == "*":
        dow = "?"
    else:
        dom = "?"
    return "cron(%s %s %s %s %s *)" % (minute, hour, dom, month, dow)


def _aws_task_definition(man, env_vars, secret_names):
    """ECS task definition with FILL_IN placeholders the user must edit.

    deploy.sh refuses to register while any placeholder remains.
    """
    slug = app_slug(man)
    port = man.docker.get("port", 8080)
    container = {
        "name": slug,
        "image": "FILL_IN: rendered by deploy.sh (ECR image URI)",
        "essential": True,
        "command": ["nova", "run", os.path.basename(man.entry)],
        "portMappings": [{"containerPort": port, "protocol": "tcp"}],
        "environment": [{"name": k, "value": v}
                        for k, v in sorted(env_vars.items())],
        "secrets": [{
            "name": "NOVA_SECRET_" + name.upper().replace("-", "_"),
            "valueFrom": ("FILL_IN: Secrets Manager ARN for secret "
                          "'%s'" % name),
        } for name in secret_names],
        "logConfiguration": {
            "logDriver": "awslogs",
            "options": {
                "awslogs-group": "/ecs/%s" % slug,
                "awslogs-region": "FILL_IN: AWS region, e.g. us-east-1",
                "awslogs-stream-prefix": "ecs",
            },
        },
    }
    return {
        "family": slug,
        "networkMode": "awsvpc",
        "requiresCompatibilities": ["FARGATE"],
        "cpu": "256",
        "memory": "512",
        "executionRoleArn": "FILL_IN: ECS task execution role ARN",
        "containerDefinitions": [container],
    }


def _aws_service_sketch(man):
    """ecs create-service shape. A sketch, not a script, because VPC
    details (subnets, security groups) are user-supplied in deploy.sh."""
    slug = app_slug(man)
    return {
        "_note": ("Service sketch for %s. The actual create/update "
                  "command lives in deploy.sh with your CLUSTER_NAME, "
                  "SUBNETS and SECURITY_GROUPS filled in." % slug),
        "serviceName": slug,
        "cluster": "FILL_IN: ECS cluster name",
        "taskDefinition": slug,
        "desiredCount": 1,
        "launchType": "FARGATE",
        "networkConfiguration": {
            "awsvpcConfiguration": {
                "subnets": ["FILL_IN: subnet-ids, comma-separated"],
                "securityGroups": ["FILL_IN: security-group-ids"],
                "assignPublicIp": "ENABLED",
            }
        },
    }


def _aws_deploy_sh(man, env_vars, cron_jobs):
    slug = app_slug(man)
    version = man.version
    # cron schedule lines: aws scheduler create-schedule per job
    sched_blocks = []
    for job in cron_jobs:
        expr = _aws_schedule_expression(job.schedule.expr)
        cname = job.name.lower().replace(" ", "-")
        sched_blocks.append(
            '''  TARGET_JSON=$(python3 - "$TASK_ARN" "$SCHED_ROLE_ARN" "$CLUSTER_ARN" "$SUBNETS" "$SECURITY_GROUPS" <<'EOF'
import json, sys
_, task_arn, role_arn, cluster_arn, subnets, sgs = sys.argv
def split(s): return [p for p in s.split(",") if p]
target = {
    "Arn": cluster_arn,
    "RoleArn": role_arn,
    "EcsParameters": {
        "TaskDefinitionArn": task_arn,
        "TaskCount": 1,
        "LaunchType": "FARGATE",
        "NetworkConfiguration": {"AwsvpcConfiguration": {
            "Subnets": split(subnets),
            "SecurityGroups": split(sgs),
            "AssignPublicIp": "ENABLED",
        }},
    },
    # Override the image's default command: run the cron file, not entry.
    "Input": json.dumps({"containerOverrides": [{
        "name": "%(slug)s",
        "command": ["nova", "run", "%(run)s"],
    }]}),
}
print(json.dumps(target))
EOF
)
  aws scheduler describe-schedule --name "%(sched)s" >/dev/null 2>&1 \\
    && aws scheduler update-schedule --name "%(sched)s" \\
         --schedule-expression "%(expr)s" --flexible-time-window Mode=OFF \\
         --target "$TARGET_JSON" \\
    || aws scheduler create-schedule --name "%(sched)s" \\
         --schedule-expression "%(expr)s" --flexible-time-window Mode=OFF \\
         --target "$TARGET_JSON"
  echo "  schedule %(sched)s ok"
''' % {"slug": slug, "run": os.path.basename(job.run_file),
       "sched": "%s-%s" % (slug, cname), "expr": expr})
    sched_section = "\n".join(sched_blocks) if sched_blocks else (
        "  echo '  no cron resources in app.nova'\n")
    return """#!/usr/bin/env bash
# Generated by `nova deploy --target aws` for %(slug)s %(version)s.
#
# Deploys the app to AWS ECS (Fargate) + EventBridge Scheduler.
#
# BEFORE RUNNING, fill in every FILL_IN placeholder below AND in
# task-definition.json (execution role ARN, secret ARNs, log region).
# You need: `aws configure` done (credentials + default region),
# docker installed, and an ECS cluster + VPC subnets + security groups.
#
# The script refuses to proceed while any FILL_IN value is unchanged.

set -euo pipefail

# ---- config: FILL IN -------------------------------------------------
AWS_REGION="FILL_IN: your AWS region, e.g. us-east-1"
ACCOUNT_ID="FILL_IN: your 12-digit AWS account id"
ECR_REPO="FILL_IN: ECR repo name, e.g. %(slug)s"
CLUSTER_NAME="FILL_IN: ECS cluster name"
SUBNETS="FILL_IN: subnet-ids, comma-separated, e.g. subnet-aaa,subnet-bbb"
SECURITY_GROUPS="FILL_IN: security-group-ids, comma-separated"
SCHED_ROLE_ARN="FILL_IN: IAM role ARN EventBridge Scheduler assumes"
# ----------------------------------------------------------------------

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
APP_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"   # <appdir>/deploy/aws -> <appdir>
IMAGE_URI="${ACCOUNT_ID}.dkr.ecr.${AWS_REGION}.amazonaws.com/${ECR_REPO}:%(version)s"

die() { echo "deploy.sh: $*" >&2; exit 1; }

# sanity: no placeholder left behind
for v in AWS_REGION ACCOUNT_ID ECR_REPO CLUSTER_NAME SUBNETS \\
         SECURITY_GROUPS SCHED_ROLE_ARN; do
  case "${!v}" in
    FILL_IN:*) die "fill in $v in deploy.sh first" ;;
  esac
done

aws sts get-caller-identity >/dev/null \\
  || die "aws credentials not configured — run 'aws configure' first"
[ -x "$(command -v docker)" ] || die "docker not found"

# 1. registry: create repo if needed, log docker in
aws ecr describe-repositories --repository-names "$ECR_REPO" \\
    --region "$AWS_REGION" >/dev/null 2>&1 \\
  || aws ecr create-repository --repository-name "$ECR_REPO" \\
       --region "$AWS_REGION" >/dev/null
aws ecr get-login-password --region "$AWS_REGION" \\
  | docker login --username AWS --password-stdin \\
      "${ACCOUNT_ID}.dkr.ecr.${AWS_REGION}.amazonaws.com"

# 2. build + push (context = app dir so Dockerfile COPYs find the tree)
docker build -f "$SCRIPT_DIR/Dockerfile" -t "$IMAGE_URI" "$APP_DIR"
docker push "$IMAGE_URI"

# 3. task definition: no FILL_IN placeholders may remain
grep -q "FILL_IN" "$SCRIPT_DIR/task-definition.json" \\
  && die "fill in the FILL_IN placeholders in task-definition.json first"
python3 - "$SCRIPT_DIR/task-definition.json" \\
    "$SCRIPT_DIR/task-definition.rendered.json" "$IMAGE_URI" <<'EOF'
import json, sys
src, dst, image = sys.argv[1], sys.argv[2], sys.argv[3]
td = json.load(open(src))
td["containerDefinitions"][0]["image"] = image
json.dump(td, open(dst, "w"), indent=2)
EOF
TASK_ARN=$(aws ecs register-task-definition --region "$AWS_REGION" \\
  --cli-input-json "file://$SCRIPT_DIR/task-definition.rendered.json" \\
  --query 'taskDefinition.taskDefinitionArn' --output text)
echo "registered task definition: $TASK_ARN"

# log group for the awslogs driver
aws logs create-log-group --log-group-name "/ecs/%(slug)s" \\
    --region "$AWS_REGION" >/dev/null 2>&1 || true

# 4. service: create once, update on later runs
if aws ecs describe-services --cluster "$CLUSTER_NAME" \\
     --services "%(slug)s" --region "$AWS_REGION" \\
     --query 'services[0].status' --output text 2>/dev/null \\
     | grep -q ACTIVE; then
  aws ecs update-service --cluster "$CLUSTER_NAME" \\
    --service "%(slug)s" --task-definition "$TASK_ARN" \\
    --region "$AWS_REGION" --force-new-deployment >/dev/null
  echo "service %(slug)s updated"
else
  aws ecs create-service --cluster "$CLUSTER_NAME" \\
    --service-name "%(slug)s" --task-definition "$TASK_ARN" \\
    --desired-count 1 --launch-type FARGATE --region "$AWS_REGION" \\
    --network-configuration \\
      "awsvpcConfiguration={subnets=[$SUBNETS],securityGroups=[$SECURITY_GROUPS],assignPublicIp=ENABLED}" \\
    >/dev/null
  echo "service %(slug)s created"
fi

# 5. cron resources -> EventBridge Scheduler -> same task, cron command
CLUSTER_ARN=$(aws ecs describe-clusters --clusters "$CLUSTER_NAME" \\
  --region "$AWS_REGION" --query 'clusters[0].clusterArn' --output text)
echo "scheduling cron resources:"
%(sched)s
echo "done."
""" % {"slug": slug, "version": version, "sched": sched_section}


def generate_aws(man, man_path, out_dir):
    """Generate AWS (ECS/Fargate) deploy artifacts into out_dir.

    Writes: Dockerfile, task-definition.json, service.json (sketch),
    deploy.sh (executable). Returns the list of written paths.
    out_dir is expected to be <appdir>/deploy/aws.
    """
    os.makedirs(out_dir, exist_ok=True)
    sources = _app_sources(man, man_path)
    env_vars = _env_vars(man)
    cron_jobs = _cron_jobs(man, man_path)
    files = {
        "Dockerfile": _dockerfile(man, sources),
        "task-definition.json":
            json.dumps(_aws_task_definition(man, env_vars,
                                            _secret_names(man)),
                       indent=2) + "\n",
        "service.json":
            json.dumps(_aws_service_sketch(man), indent=2) + "\n",
        "deploy.sh": _aws_deploy_sh(man, env_vars, cron_jobs),
    }
    written = []
    for name, content in files.items():
        path = os.path.join(out_dir, name)
        _write(path, content, executable=(name == "deploy.sh"))
        written.append(path)
    return written


