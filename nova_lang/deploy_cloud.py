# deploy_cloud.py — cloud deploy targets for `nova deploy --target aws|gcp`.
#
# v2 roadmap item: real deployment artifacts for AWS (ECS-flavored) and
# GCP (Cloud Run). These are pure *generators* — they read the manifest
# and write Dockerfiles + provider configs + deploy.sh scripts. They
# never call out to `aws`/`gcloud`/`docker`; the generated deploy.sh
# does the live work, after the user fills in the clearly-marked
# placeholders (credentials, registry, project/region, network).
#
# Out-dir convention: generate_aws writes into <appdir>/deploy/aws and
# generate_gcp into <appdir>/deploy/gcp. The generated deploy.sh derives
# the app dir as <out>/../.. (i.e. <appdir>) so the Docker build context
# is the app tree that holds app.nova, the Nova toolchain, and the
# entry's transitive imports.

import json
import os
import stat

from .manifest import ManifestError  # re-exported for wiring convenience


# ----------------------------------------------------------------------
# shared helpers
# ----------------------------------------------------------------------

def app_slug(man):
    """Image/service name: lowercased, spaces -> dashes."""
    return man.name.lower().replace(" ", "-")


def _app_sources(man, man_path):
    """Entry + transitive imports + cron run files, relative to appdir.

    Relative paths are what the Dockerfile COPYs (build context = appdir).
    Missing entry files are listed anyway so generation never crashes;
    the docker build itself will fail loudly if they're really absent.
    """
    appdir = os.path.dirname(os.path.abspath(man_path))
    entry = os.path.join(appdir, man.entry)
    seen = []
    if os.path.isfile(entry):
        try:
            from .cli import _transitive_imports
            for f in _transitive_imports(entry):
                rel = os.path.relpath(f, appdir)
                if rel not in seen:
                    seen.append(rel)
        except Exception:
            seen = [man.entry]
    else:
        seen = [man.entry]
    for kind, _name, opts in man.resources:
        if kind == "cron":
            run = opts.get("run")
            if run and run not in seen:
                seen.append(run)
    return seen


def _env_vars(man):
    """Non-secret env vars for the deployment: prod block, else dev.

    Same convention as `nova deploy --target local`: keys uppercased.
    """
    env = man.envs.get("prod") or man.envs.get("dev") or {}
    return {k.upper(): str(v) for k, v in env.items()}


def _secret_names(man):
    return [name for kind, name, _opts in man.resources
            if kind == "secret"]


def _cron_jobs(man, man_path):
    """CronJob list from the manifest's `resource cron` entries."""
    from .scheduler import jobs_from_manifest
    try:
        return jobs_from_manifest(man, man_path)
    except ValueError as e:
        raise ManifestError("app.nova: %s" % e)


def _dockerfile(man, sources):
    """The v1 image shape: python + Nova toolchain (stdlib only)."""
    base = man.docker.get("base", "python:3.12-slim")
    port = man.docker.get("port", 8080)
    entry_base = os.path.basename(man.entry)
    lines = [
        "# Generated by `nova deploy --target <aws|gcp>` for %s %s."
        % (man.name, man.version),
        "# Build context must be the app dir (holds nova_lang/, nova, app.nova).",
        "FROM %s" % base,
        "WORKDIR /app",
        "# Nova toolchain (pure Python, stdlib only — no pip installs)",
        "COPY nova_lang /opt/nova-lang/nova_lang",
        "COPY nova /opt/nova-lang/nova",
        'ENV PATH="/opt/nova-lang:${PATH}"',
        "# App sources (entry + transitive imports + cron run files)",
    ]
    for src in sources:
        lines.append("COPY %s /app/%s" % (src, src))
    lines.append("ENV NOVA_THREADING=%s" % man.threading)
    lines.append("EXPOSE %s" % port)
    lines.append('CMD ["nova", "run", "%s"]' % entry_base)
    return "\n".join(lines) + "\n"


def _write(path, content, executable=False):
    with open(path, "w") as fh:
        fh.write(content)
    if executable:
        st = os.stat(path)
        os.chmod(path, st.st_mode | stat.S_IXUSR | stat.S_IXGRP
                 | stat.S_IXOTH)


