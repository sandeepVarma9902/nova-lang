def _gcp_service_yaml(man, env_vars, secret_names):
    """Cloud Run service YAML — declarative sketch.

    deploy.sh uses `gcloud run deploy` with flags (the live path); this
    YAML is the equivalent declarative shape. %%IMAGE_URI%% is filled by
    deploy.sh's push step; secret paths are user-supplied.
    """
    slug = app_slug(man)
    port = man.docker.get("port", 8080)
    env_lines = "".join(
        '        - name: %s\n          value: "%s"\n' % (k, v)
        for k, v in sorted(env_vars.items()))
    secret_lines = "".join(
        '        # - name: NOVA_SECRET_%s\n'
        '        #   valueFrom:\n'
        '        #     secretKeyRef:\n'
        '        #       name: FILL_IN-secret-name-for-%s\n'
        '        #       key: latest\n'
        % (name.upper().replace("-", "_"), name)
        for name in secret_names)
    return """# Generated by `nova deploy --target gcp` for %(slug)s %(version)s.
# Declarative sketch of the Cloud Run service. deploy.sh performs the
# same deploy via `gcloud run deploy`; keep them in sync by hand if you
# edit this file. %%IMAGE_URI%% is filled in by the deploy script.
apiVersion: serving.knative.dev/v1
kind: Service
metadata:
  name: %(slug)s
spec:
  template:
    metadata:
      annotations:
        autoscaling.knative.dev/maxScale: "10"
    spec:
      containers:
        - image: %%IMAGE_URI%%
          ports:
            - containerPort: %(port)s
          command: ["nova", "run", "%(entry)s"]
          env:
%(env)s%(secrets)s""" % {"slug": slug, "version": man.version,
                          "port": port,
                          "entry": os.path.basename(man.entry),
                          "env": env_lines or "            # no env vars\n",
                          "secrets": secret_lines}


def _gcp_deploy_sh(man, env_vars, cron_jobs):
    slug = app_slug(man)
    version = man.version
    env_flag = ",".join("%s=%s" % (k, v)
                        for k, v in sorted(env_vars.items()))
    port = man.docker.get("port", 8080)
    sched_blocks = []
    for job in cron_jobs:
        cname = job.name.lower().replace(" ", "-")
        sched_blocks.append(
            '''  JOB="%(sched)s"
  URI="${SERVICE_URL}/cron/%(cname)s"
  if gcloud scheduler jobs describe "$JOB" --location="$REGION" \\
       >/dev/null 2>&1; then
    gcloud scheduler jobs update http "$JOB" --location="$REGION" \\
      --schedule="%(expr)s" --uri="$URI" --http-method=POST --quiet
  else
    gcloud scheduler jobs create http "$JOB" --location="$REGION" \\
      --schedule="%(expr)s" --uri="$URI" --http-method=POST \\
      --description="nova cron %(name)s" --quiet
  fi
  echo "  schedule $JOB ok"''' % {"sched": "%s-%s" % (slug, cname),
                                  "cname": cname, "expr": job.schedule.expr,
                                  "name": job.name})
    sched_section = "\n".join(sched_blocks) if sched_blocks else (
        '  echo "  no cron resources in app.nova"\n')
    return """#!/usr/bin/env bash
# Generated by `nova deploy --target gcp` for %(slug)s %(version)s.
#
# Deploys the app to Cloud Run + Cloud Scheduler.
#
# BEFORE RUNNING, fill in every FILL_IN placeholder below. You need:
# `gcloud auth login` done, a GCP project with the Cloud Run, Artifact
# Registry and Cloud Scheduler APIs enabled, docker installed, and
# billing enabled on the project.
#
# The script refuses to proceed while any FILL_IN value is unchanged.

set -euo pipefail

# ---- config: FILL IN -------------------------------------------------
PROJECT_ID="FILL_IN: your GCP project id"
REGION="FILL_IN: region, e.g. us-central1"
AR_REPO="FILL_IN: Artifact Registry repo name, e.g. %(slug)s"
# ----------------------------------------------------------------------

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
APP_DIR="$(cd "$SCRIPT_DIR/../.." && pwd)"   # <appdir>/deploy/gcp -> <appdir>
REGISTRY="${REGION}-docker.pkg.dev"
IMAGE_URI="${REGISTRY}/${PROJECT_ID}/${AR_REPO}/%(slug)s:%(version)s"

die() { echo "deploy.sh: $*" >&2; exit 1; }

for v in PROJECT_ID REGION AR_REPO; do
  case "${!v}" in
    FILL_IN:*) die "fill in $v in deploy.sh first" ;;
  esac
done

[ -x "$(command -v gcloud)" ] || die "gcloud CLI not found"
[ -x "$(command -v docker)" ] || die "docker not found"
gcloud auth list --filter=status:ACTIVE --format="value(account)" \\
  | grep -q . || die "not logged in — run 'gcloud auth login' first"
gcloud config set project "$PROJECT_ID" >/dev/null

# 1. Artifact Registry repo (create if missing)
gcloud artifacts repositories describe "$AR_REPO" --location="$REGION" \\
    >/dev/null 2>&1 \\
  || gcloud artifacts repositories create "$AR_REPO" \\
       --repository-format=docker --location="$REGION" \\
       --description="Nova app images" --quiet
gcloud auth configure-docker "$REGISTRY" --quiet

# 2. build + push (context = app dir so Dockerfile COPYs find the tree)
docker build -f "$SCRIPT_DIR/Dockerfile" -t "$IMAGE_URI" "$APP_DIR"
docker push "$IMAGE_URI"

# 3. Cloud Run service (flags mirror service.yaml)
gcloud run deploy "%(slug)s" \\
  --image="$IMAGE_URI" \\
  --region="$REGION" --platform=managed \\
  --allow-unauthenticated \\
  --port=%(port)s \\
  --max-instances=10 \\
%(env_line)s  --quiet
SERVICE_URL=$(gcloud run services describe "%(slug)s" --region="$REGION" \\
  --format="value(status.url)")
echo "service url: $SERVICE_URL"

# 4. cron resources -> Cloud Scheduler (HTTP POST per job).
# NOTE: the deployed service runs `nova run <entry>`; it does not serve
# HTTP. Point SERVICE_URL at an HTTP endpoint of your app, or have the
# entry listen on $PORT, before these schedules can fire usefully.
echo "scheduling cron resources:"
%(sched)s
echo "done."
""" % {"slug": slug, "version": version, "port": port,
       "env_line": ('  --set-env-vars="%s" \\\n' % env_flag)
                   if env_flag else "",
       "sched": sched_section}


def generate_gcp(man, man_path, out_dir):
    """Generate GCP (Cloud Run) deploy artifacts into out_dir.

    Writes: Dockerfile, service.yaml (declarative sketch), deploy.sh
    (executable). Returns the list of written paths.
    out_dir is expected to be <appdir>/deploy/gcp.
    """
    os.makedirs(out_dir, exist_ok=True)
    sources = _app_sources(man, man_path)
    env_vars = _env_vars(man)
    files = {
        "Dockerfile": _dockerfile(man, sources),
        "service.yaml": _gcp_service_yaml(man, env_vars,
                                          _secret_names(man)),
        "deploy.sh": _gcp_deploy_sh(man, env_vars, _cron_jobs(man, man_path)),
    }
    written = []
    for name, content in files.items():
        path = os.path.join(out_dir, name)
        _write(path, content, executable=(name == "deploy.sh"))
        written.append(path)
    return written
