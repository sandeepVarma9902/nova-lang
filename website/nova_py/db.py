# db.py — Nova database nativity.
#
# Two halves:
#  1. `nova db pull --dsn sqlite:///app.db --out models.nova`: inspect the
#     schema with stdlib sqlite3 and generate Nova data-class models plus
#     a .nova-schema.json used for check-time column validation.
#     postgres/mysql need a real driver — dbOpen says so honestly.
#  2. Runtime: VDb (one sqlite3 connection) + VQuery (fluent builder).
#     Queries return rows as Json values; generated `fromJson` helpers map
#     them onto the pulled model types.

import datetime
import json as _json
import os
import re
import sqlite3


class DbError(Exception):
    pass


# ------------------------------------------------------------------ DSN ----
def parse_dsn(dsn):
    """Split a DSN into (driver, path). Only sqlite is implemented."""
    if dsn.startswith("sqlite:///"):
        return "sqlite", dsn[len("sqlite:///"):]
    if dsn.startswith("postgres://") or dsn.startswith("postgresql://"):
        raise DbError("postgres needs a driver (see docs/v2.1-database.md)")
    if dsn.startswith("mysql://"):
        raise DbError("mysql needs a driver (see docs/v2.1-database.md)")
    raise DbError("unsupported DSN '%s' — want sqlite:///<path>" % dsn)


# ----------------------------------------------------------------- pull ----
_SQLITE_TYPE = [
    (("INT",), "Int"),
    (("INTEGER",), "Int"),
    (("REAL", "FLOA", "DOUB"), "Float"),
    (("CHAR", "CLOB", "TEXT", "VARCHAR"), "String"),
    (("BLOB",), "String"),  # decoded as latin-1; documented
]


def _nova_type(coltype, notnull, pk):
    base = "String"
    up = (coltype or "").upper()
    for keys, nova in _SQLITE_TYPE:
        if any(k in up for k in keys):
            base = nova
            break
    if pk or notnull:
        return base
    return "Option[%s]" % base


def _class_name(table):
    # users -> User, blog_posts -> BlogPost (naive singularization)
    parts = table.split("_")
    if len(parts) == 1 and parts[0].endswith("s") \
            and not parts[0].endswith("ss") and len(parts[0]) > 1:
        parts[0] = parts[0][:-1]
    return "".join(p[:1].upper() + p[1:] for p in parts)


def pull_sqlite(dsn, out_path):
    """Generate models.nova + .nova-schema.json from a sqlite DSN."""
    _, path = parse_dsn(dsn)
    if not os.path.isfile(path):
        raise DbError("sqlite file not found: %s" % path)
    conn = sqlite3.connect(path)
    try:
        tables = [r[0] for r in conn.execute(
            "SELECT name FROM sqlite_master WHERE type='table' "
            "AND name NOT LIKE 'sqlite_%' ORDER BY name")]
        if not tables:
            raise DbError("no tables found in %s" % path)
        schema = {"tables": {}}
        chunks = []
        for table in tables:
            cols = conn.execute(
                "PRAGMA table_info(%s)" % _quote_ident(table)).fetchall()
            # (cid, name, type, notnull, dflt, pk)
            fields = []
            colmap = {}
            for _, name, ctype, notnull, _, pk in cols:
                nt = _nova_type(ctype, notnull, pk)
                fields.append((name, nt))
                colmap[name] = nt
            schema["tables"][table] = colmap
            cname = _class_name(table)
            chunks.append("data class %s(%s)" % (
                cname, ", ".join("%s: %s" % (n, t) for n, t in fields)))
            chunks.append("")
            chunks.append("fn %sFromJson(j: Json) -> Result[%s, String] {"
                          % (cname[0].lower() + cname[1:], cname))
            for fname, ftype in fields:
                expr = _from_json_expr(fname, ftype)
                # The match must start on the `let` line (significant
                # newlines); its arms may span lines.
                first, rest = expr.split("\n", 1)
                chunks.append("  let _%s = %s" % (fname, first))
                chunks.append(
                    "\n".join("  " + ln for ln in rest.split("\n")))
            chunks.append("  return Ok(%s(%s))" % (
                cname, ", ".join(
                    "%s: %s" % (n, ("_%s?" % n)
                                if not t.startswith("Option[") else "_%s" % n)
                    for n, t in fields)))
            chunks.append("}")
            chunks.append("")
        header = ("// Generated by `nova db pull --dsn %s` on %s.\n"
                  "// DO NOT EDIT — regenerate instead.\n\n"
                  % (dsn, datetime.datetime.now().strftime("%Y-%m-%d")))
        with open(out_path, "w") as fh:
            fh.write(header + "\n".join(chunks))
        schema_path = os.path.join(os.path.dirname(os.path.abspath(out_path)),
                                   ".nova-schema.json")
        with open(schema_path, "w") as fh:
            _json.dump(schema, fh, indent=2)
        return tables
    finally:
        conn.close()


def _json_conv(ftype):
    return {"Int": "jsonInt", "Float": "jsonFloat", "String": "jsonStr",
            "Bool": "jsonBool"}.get(ftype, "jsonStr")


def _from_json_expr(fname, ftype):
    # Build a match expression over jsonGet(j, fname):
    # required fields -> Result[T, String]; Option fields -> Option[T].
    # No `?` mixing: required fields are unwrapped with `?` at the
    # construction site (Result propagates Err correctly there).
    if ftype.startswith("Option["):
        conv = _json_conv(ftype[7:-1])
        lines = [
            'match jsonGet(j, "%s") {' % fname,
            '  Some(v) => match %s(v) { Some(x) => Some(x), None => None },'
            % conv,
            '  None => None',
            '}',
        ]
        return "\n".join(lines)
    conv = _json_conv(ftype)
    lines = [
        'match jsonGet(j, "%s") {' % fname,
        '  Some(v) => match %s(v) { Some(x) => Ok(x), None => Err("bad %s") },'
        % (conv, fname),
        '  None => Err("missing %s")' % fname,
        '}',
    ]
    return "\n".join(lines)


def _quote_ident(name):
    if not re.match(r"^[A-Za-z_][A-Za-z0-9_]*$", name):
        raise DbError("unsafe identifier '%s'" % name)
    return '"%s"' % name


# --------------------------------------------------------------- runtime ----
class VDb:
    def __init__(self, conn):
        self.conn = conn


class VQuery:
    def __init__(self, db, table):
        self.db = db
        self.table = table
        self._select = ["*"]
        self._wheres = []   # [(col, op, value)]
        self._order = None  # (col, dir)
        self._limit = None

    def clone(self):
        q = VQuery(self.db, self.table)
        q._select = list(self._select)
        q._wheres = list(self._wheres)
        q._order = self._order
        q._limit = self._limit
        return q

    def sql(self):
        parts = ["SELECT %s FROM %s" % (
            ", ".join(_quote_ident(c) if c != "*" else "*"
                      for c in self._select),
            _quote_ident(self.table))]
        params = []
        if self._wheres:
            conds = []
            for col, op, val in self._wheres:
                if op == "like":
                    conds.append("%s LIKE ?" % _quote_ident(col))
                else:
                    conds.append("%s %s ?" % (_quote_ident(col), op))
                params.append(val)
            parts.append("WHERE " + " AND ".join(conds))
        if self._order:
            col, direction = self._order
            d = "DESC" if direction.lower() == "desc" else "ASC"
            parts.append("ORDER BY %s %s" % (_quote_ident(col), d))
        if self._limit is not None:
            parts.append("LIMIT %d" % self._limit)
        return " ".join(parts), params


def open_db(dsn):
    driver, path = parse_dsn(dsn)
    if driver != "sqlite":
        raise DbError("driver '%s' not implemented" % driver)
    try:
        conn = sqlite3.connect(path)
        conn.row_factory = sqlite3.Row
    except Exception as e:
        raise DbError("open %s: %s" % (path, e))
    return VDb(conn)


def exec_sql(db, sql):
    try:
        cur = db.conn.execute(sql)
        db.conn.commit()
        return cur.rowcount
    except Exception as e:
        raise DbError(str(e))


def run_query(q):
    sql, params = q.sql()
    try:
        cur = q.db.conn.execute(sql, params)
        cols = [d[0] for d in cur.description or []]
        rows = [dict(zip(cols, r)) for r in cur.fetchall()]
        return rows
    except Exception as e:
        raise DbError(str(e))
